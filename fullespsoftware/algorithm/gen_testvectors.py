"""Generate algorithm/testvectors.csv from the Python reference implementation.

The C++ port in firmware/lib/icedetect must reproduce every row exactly. Regenerate after any change
to icedetect.py:   python -m algorithm.gen_testvectors

Format: lines starting with "# params k=v ..." reset the detector and set parameter overrides for the
rows that follow. Row columns: cap_delta_pct,res_log10,temp_c,expect_state,expect_thickness_mm,expect_defrost
("nan" = input not available).
"""
from __future__ import annotations

import math
import os
import random

from algorithm.icedetect import Detector, Params
from simulator import scenario

OUT = os.path.join(os.path.dirname(__file__), "testvectors.csv")


def fmt(x) -> str:
    return "nan" if x is None or (isinstance(x, float) and math.isnan(x)) else repr(float(x))


def section(lines: list[str], title: str, overrides: dict, inputs: list[tuple]) -> None:
    params = Params(**overrides)
    det = Detector(params)
    lines.append(f"# params {' '.join(f'{k}={v}' for k, v in overrides.items())}  [{title}]")
    for cap, r, t in inputs:
        out = det.step(cap, r, t)
        lines.append(",".join([fmt(cap), fmt(r), fmt(t), str(int(out.state)),
                               repr(float(out.thickness_mm)), str(int(out.defrost_request))]))


def cycle(seed: int, cycle_s: float, step_s: float) -> list[tuple]:
    rng = random.Random(seed)
    n = int(cycle_s / step_s)
    return [(v["cap_delta_pct"], v["log10_ohm"], v["temp_c"])
            for v in (scenario.at(i * step_s, cycle_s, rng) for i in range(n))]


def main() -> None:
    nan = float("nan")
    lines = ["# columns: cap_delta_pct,res_log10,temp_c,expect_state,expect_thickness_mm,expect_defrost",
             "# generated by algorithm/gen_testvectors.py from algorithm/icedetect.py: do not edit"]
    section(lines, "full cycle, default params", {}, cycle(1, 600, 2))
    section(lines, "second noise seed", {}, cycle(7, 600, 2))
    section(lines, "no debounce, early defrost", {"confirm_windows": 1, "defrost_on_mm": 1.0,
                                                  "defrost_on_windows": 1, "defrost_off_windows": 1},
            cycle(3, 600, 3))
    section(lines, "strict thresholds", {"deposit_pct": 12.0, "ice_pct": 30.0, "freeze_c": -1.0,
                                         "mm_per_pct": 0.2, "max_mm": 6.0}, cycle(5, 600, 2))
    # hand-made edge cases: missing inputs, no resistive channel, negative capacitance direction,
    # sensor fault in the middle of a deposit, state held through single glitches
    edge = []
    edge += [(nan, 6.9, 3.0)] * 3                         # no baseline -> unknown, no request
    edge += [(0.0, 6.9, 3.0)] * 3                         # clear
    edge += [(-25.0, nan, -5.0)] * 4                      # negative delta, no resistive channel: ice
    edge += [(-25.0, nan, nan)] * 3                       # temperature sensor fault: unknown, request released
    edge += [(30.0, 6.4, -5.0)] * 5                       # back to ice, request again
    edge += [(0.0, 6.9, -5.0)] + [(30.0, 6.4, -5.0)] * 3  # single glitch must not change the state
    edge += [(2.0, 5.0, 3.0)] * 3                         # liquid film, below deposit threshold
    section(lines, "edge cases", {}, edge)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({sum(1 for l in lines if not l.startswith('#'))} rows)")


if __name__ == "__main__":
    main()
